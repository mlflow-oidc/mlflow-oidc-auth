def _routes():
    for router in (user_permissions.user_permissions_router, group_permissions.group_permissions_router):
        for route in router.routes:
            if isinstance(route, APIRoute):
                for method in route.methods:
                    yield method, route


ROUTES = list(_routes())


def _route_id(item):
    method, route = item
    return f"{method} {route.path}"


def _calls(dependant):
    """Every dependency callable in a dependant tree, depth first."""
    found = []
    for sub in dependant.dependencies:
        found.append(sub.call)
        found.extend(_calls(sub))
    return found


def test_table_lists_every_route_exactly():
    actual = {(method, route.path) for method, route in ROUTES}
    assert len(actual) == len(ROUTES), "two routes share a method and path"
    assert sorted(actual - EXPECTED.keys()) == [], "routes with no expected gate: add them to the table"
    assert sorted(EXPECTED.keys() - actual) == [], "table entries with no route"


def _assert_reads_target_from_path(route, dependency):
    """A manage check must take its target from the route's own path, never from a query string."""
    route_params = {param.name for param in route.dependant.path_params}
    gate = next(sub for sub in route.dependant.dependencies if sub.call is dependency)
    gate_params = {param.name for param in gate.path_params}
    assert gate_params, f"{dependency.__name__} no longer reads a path parameter"
    assert gate_params <= route_params, f"{route.name}: {dependency.__name__} reads {gate_params - route_params} outside the route path"
    assert not gate.query_params, f"{route.name}: {dependency.__name__} reads a query parameter"


@pytest.mark.parametrize("item", ROUTES, ids=_route_id)
def test_route_has_its_gate(item):
    method, route = item
    gate = EXPECTED[(method, route.path)]
    direct = [sub.call for sub in route.dependant.dependencies]
    if gate in GATES:
        dependency = GATES[gate]
        assert dependency in direct, f"{method} {route.path} ({route.name}) lost its {dependency.__name__} dependency"
        if gate != ADMIN:
            _assert_reads_target_from_path(route, dependency)
    elif gate == FILTERED:
        # Only a collection may be an ungated, caller-filtered listing; one grant needs a gate.
        resource_params = {param.name for param in route.dependant.path_params} - SUBJECT_PARAMS
        assert method == "GET" and not resource_params, f"{method} {route.path} ({route.name}) is labelled FILTERED but addresses one resource"
        assert get_username in direct and get_is_admin in direct, f"{route.name} must resolve the caller and whether they are an admin"
    elif gate == SIGNED_IN:
        assert direct[0] is get_username and method == "GET"
    else:  # pragma: no cover - the table holds only the gates above
        pytest.fail(f"unknown gate {gate!r}")
    unexpected = [call.__name__ for name, call in GATES.items() if name != gate and call in _calls(route.dependant)]
    assert not unexpected, f"{route.name} has gates the table does not list: {unexpected}"


# Every registered-model and prompt grant gate decides through effective_registry_permission, which
# judges the target by its real kind (#479).
GROUP_GATES = [
    (check_group_registered_model_manage_permission, "name"),
    (check_group_prompt_manage_permission, "prompt_name"),
    (check_user_prompt_manage_permission, "name"),
]
GATE_IDS = ["model", "prompt", "user-prompt"]


@pytest.mark.parametrize("gate, target", GROUP_GATES, ids=GATE_IDS)
async def test_group_gate_refuses_a_non_manager(gate, target):
    """A non-admin without MANAGE gets a 403, decided on the route's own resource for that caller."""
    effective = MagicMock(return_value=SimpleNamespace(permission=SimpleNamespace(can_manage=False)))
    with patch.object(dependencies, "effective_registry_permission", effective):
        with pytest.raises(HTTPException) as raised:
            await gate(**{target: "res-a"}, current_username="mallory", is_admin=False)
    assert raised.value.status_code == 403
    assert effective.call_args.args == ("res-a", "mallory")


@pytest.mark.parametrize("gate, target", GROUP_GATES, ids=GATE_IDS)
async def test_group_gate_lets_a_manager_and_an_admin_through(gate, target):
    effective = MagicMock(return_value=SimpleNamespace(permission=SimpleNamespace(can_manage=True)))
    with patch.object(dependencies, "effective_registry_permission", effective):
        assert await gate(**{target: "res-a"}, current_username="alice", is_admin=False) is None
    refusing = MagicMock(return_value=SimpleNamespace(permission=SimpleNamespace(can_manage=False)))
    with patch.object(dependencies, "effective_registry_permission", refusing):
        assert await gate(**{target: "res-a"}, current_username="root", is_admin=True) is None
    refusing.assert_not_called()


def _route(op, auth, path="/x/{name}", params=(("name", str, "n"),)):
    from mlflow_oidc_auth.routers._permission_routes import Route

    return Route(
        name=f"{op}_x",
        op=op,
        path=path,
        summary="s",
        description="d",
        tag="t",
        params=params,
        auth=auth,
        call=lambda a: None,
        respond=lambda a, r: r,
        response_model=None,
    )


@pytest.mark.parametrize("op", ["get", "create", "update", "delete"])
def test_factory_refuses_a_route_on_one_grant_without_a_gate(op):
    """auth=CALLER only identifies the caller: a route on one grant generated with it would be open to anyone."""
    from mlflow_oidc_auth.routers._permission_routes import ADMIN, CALLER, add_route

    with pytest.raises(ValueError, match="needs an authorization dependency"):
        add_route(APIRouter(), _route(op, CALLER))
    add_route(APIRouter(), _route(op, ADMIN))  # a gate makes it valid


def test_factory_allows_a_caller_only_collection_listing():
    from mlflow_oidc_auth.routers._permission_routes import CALLER, add_route

