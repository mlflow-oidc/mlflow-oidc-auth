"""Negative guard: every user and group permission route keeps the authorization it has today (#459).

The grant routes of ``routers/user_permissions.py`` and ``routers/group_permissions.py`` are
generated by ``routers/_permission_routes.py``. A route generated without its permission
dependency, or with a weaker one, is an unauthorized grant-management endpoint. This test pins,
route by route, which gate each one has, from the explicit table below. It fails when:

* a route is added, removed or moved without updating the table,
* a route's gate dependency is removed or swapped for another,
* a ``check_*_manage_permission`` gate reads its target from anything but the route's own path,
* an inline check (the group registered-model and prompt routes) stops refusing a non-manager.
"""

